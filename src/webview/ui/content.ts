import DOMPurify from 'dompurify';
import type { RenderedBlock } from '../render/markdown';
import type { MermaidRenderer } from '../render/mermaid';
import { closestBlock, h, isMod } from './dom';

export interface ContentHooks {
  isEditMode(): boolean;
  isReadOnly(): boolean;
  editBlock(blockEl: HTMLElement, event: MouseEvent): void;
  toggleTask(line: number): void;
  openLink(href: string): void;
  copy(text: string, message: string): void;
  zoom(el: Element): void;
}

export interface ResourceRoots {
  base: string;
  root?: string;
}

const SANITIZE = {
  FORBID_TAGS: ['style', 'form', 'base', 'meta', 'link'],
  ADD_ATTR: ['loading', 'align'],
};

// Heading ids are generated by us (GitHub-style slugs). DOMPurify's clobbering
// guard would drop ones like "images" or "forms", breaking #links, so keep them.
DOMPurify.addHook('uponSanitizeAttribute', (node, data) => {
  if (data.attrName === 'id' && /^H[1-6]$/.test(node.nodeName) && /^[\p{L}\p{M}\p{N}_-]+$/u.test(data.attrValue)) {
    data.forceKeepAttr = true;
  }
});

/** Renders blocks into the page, reusing DOM nodes whose content didn't change. */
export class ContentView {
  readonly el: HTMLElement;
  resources: ResourceRoots = { base: '' };

  constructor(
    private readonly hooks: ContentHooks,
    private readonly mermaid: MermaidRenderer,
  ) {
    this.el = h('article', { class: 'rmm-content', attrs: { id: 'content' } });
    this.el.addEventListener('click', (e) => this.onClick(e));
  }

  render(blocks: RenderedBlock[]): void {
    const pool = new Map<string, HTMLElement[]>();
    for (const node of Array.from(this.el.children) as HTMLElement[]) {
      const key = node.dataset.key ?? '';
      const list = pool.get(key) ?? [];
      list.push(node);
      pool.set(key, list);
    }

    const created: HTMLElement[] = [];
    const next = blocks.map((block) => {
      let node = pool.get(block.key)?.shift();
      if (!node) {
        node = this.createNode(block);
        created.push(node);
      }
      node.dataset.start = String(block.start);
      node.dataset.end = String(block.end);
      return node;
    });

    let ref: ChildNode | null = this.el.firstChild;
    for (const node of next) {
      if (node === ref) {
        ref = ref.nextSibling;
      } else {
        this.el.insertBefore(node, ref);
      }
    }
    for (const leftovers of pool.values()) {
      leftovers.forEach((node) => node.remove());
    }

    created.forEach((node) => this.enhance(node));
  }

  /** Re-run theme-dependent enhancements (Mermaid) on every block. */
  refreshDiagrams(): void {
    this.mermaid.enhance(this.el);
  }

  private createNode(block: RenderedBlock): HTMLElement {
    const node = h('div', {
      class: `rmm-block rmm-kind-${block.kind}${block.start < 0 ? ' is-generated' : ''}`,
      data: { key: block.key, kind: block.kind },
    });
    const body = h('div', { class: 'rmm-block-body' });
    body.innerHTML = DOMPurify.sanitize(block.html, SANITIZE) as string;
    node.append(body);
    return node;
  }

  private enhance(node: HTMLElement): void {
    node.querySelectorAll<HTMLElement>('img[src], video[src], audio[src], source[src]').forEach((el) => {
      const src = el.getAttribute('src') ?? '';
      const resolved = this.resolveUrl(src);
      if (resolved !== src) {
        el.setAttribute('src', resolved);
      }
    });
    node.querySelectorAll<HTMLAnchorElement>('a[href]').forEach((a) => {
      const href = a.getAttribute('href') ?? '';
      if (/^[a-z][a-z0-9+.-]*:/i.test(href)) {
        a.title ||= href;
      }
    });
    this.mermaid.enhance(node);
  }

  private resolveUrl(url: string): string {
    if (!url || /^(?:[a-z][a-z0-9+.-]*:|\/\/|#)/i.test(url) || !this.resources.base) {
      return url;
    }
    const absolute = url.startsWith('/');
    const base = absolute && this.resources.root ? this.resources.root : this.resources.base;
    try {
      return new URL(absolute ? url.slice(1) : url, base.endsWith('/') ? base : `${base}/`).href;
    } catch {
      return url;
    }
  }

  private onClick(e: MouseEvent): void {
    const target = e.target as HTMLElement;

    const copyBtn = target.closest<HTMLElement>('.rmm-code-copy');
    if (copyBtn) {
      const code = copyBtn.closest('.rmm-code')?.querySelector('pre code')?.textContent ?? '';
      this.hooks.copy(code, 'Code copied');
      flash(copyBtn);
      return;
    }

    const action = target.closest<HTMLElement>('[data-action]');
    if (action) {
      const diagram = action.closest<HTMLElement>('.rmm-mermaid');
      if (action.dataset.action === 'mermaid-copy' && diagram) {
        this.hooks.copy(diagram.dataset.code ?? '', 'Diagram source copied');
        flash(action);
      } else if (action.dataset.action === 'mermaid-zoom' && diagram) {
        const svg = diagram.querySelector('svg');
        if (svg) {
          this.hooks.zoom(svg);
        }
      }
      return;
    }

    const checkbox = target.closest<HTMLInputElement>('input.rmm-task');
    if (checkbox) {
      e.preventDefault();
      if (!this.hooks.isReadOnly()) {
        this.hooks.toggleTask(Number(checkbox.dataset.line));
      }
      return;
    }

    const editing = this.hooks.isEditMode();
    const link = target.closest<HTMLAnchorElement>('a[href]');
    if (link && (!editing || isMod(e))) {
      e.preventDefault();
      this.hooks.openLink(link.getAttribute('href') ?? '');
      return;
    }
    if (link) {
      e.preventDefault();
    }

    if (editing) {
      const block = closestBlock(target);
      const selection = window.getSelection();
      if (block && !block.classList.contains('is-editing') && (!selection || selection.isCollapsed)) {
        if (target.closest('summary')) {
          e.preventDefault();
        }
        this.hooks.editBlock(block, e);
      }
      return;
    }

    if (target instanceof HTMLImageElement && !target.closest('a')) {
      this.hooks.zoom(target);
    }
  }
}

function flash(button: HTMLElement): void {
  const iconEl = button.querySelector('.codicon');
  if (!iconEl) {
    return;
  }
  iconEl.classList.replace('codicon-copy', 'codicon-check');
  button.classList.add('is-done');
  setTimeout(() => {
    iconEl.classList.replace('codicon-check', 'codicon-copy');
    button.classList.remove('is-done');
  }, 1400);
}
